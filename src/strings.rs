/// Supported languages: code, native name, table.
pub static LANGUAGES: [(&str, &str, &Strings); 6] = [
    ("en", "English", &EN),
    ("de", "Deutsch", &DE),
    ("fr", "Français", &FR),
    ("es", "Español", &ES),
    ("it", "Italiano", &IT),
    ("tr", "Türkçe", &TR),
];

static CURRENT: AtomicUsize = AtomicUsize::new(0);

/// Selects the language for a code such as "de", "de-DE" or "de_DE.UTF-8" (unknown: English).
pub fn set(code: &str) {
    let short = code.get(..2).unwrap_or("").to_ascii_lowercase();
    let index = LANGUAGES.iter().position(|(c, _, _)| *c == short).unwrap_or(0);
    CURRENT.store(index, Ordering::Relaxed);
}

pub fn current() -> &'static Strings {
    LANGUAGES[CURRENT.load(Ordering::Relaxed)].2
}

/// The TV's UI language (webOS keeps it in localeInfo); on desktop VISION_LANG or LANG.
pub fn system_language() -> String {
    let tv = std::fs::read_to_string("/var/luna/preferences/localeInfo").ok().and_then(|text| {
        let start = text.find('{')?;
        let value: serde_json::Value = serde_json::Deserializer::from_str(&text[start..]).into_iter().next()?.ok()?;
        value.pointer("/localeInfo/locales/UI").and_then(|v| v.as_str()).map(str::to_string)
    });
    tv.or_else(|| std::env::var("VISION_LANG").ok())
        .or_else(|| std::env::var("LANG").ok())
        .unwrap_or_else(|| "en".into())
}

/// Every character the UI may draw from these strings (for glyph prewarming).
pub fn charset(strings: &Strings) -> String {
    let mut all = String::new();
    for text in strings.texts() {
        all.push_str(text);
        all.push_str(&text.to_uppercase());
    }
    for (_, name, _) in LANGUAGES.iter() {
        all.push_str(name);
    }
    all
}
