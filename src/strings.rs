impl Strings {
    /// Short description for a WMO weather code.
    pub fn weather(&self, code: u32) -> &'static str {
        self.weather[match code {
            0 => 0,
            1 => 1,
            2 => 2,
            3 => 3,
            45 | 48 => 4,
            51..=57 => 5,
            61..=67 => 6,
            71..=77 | 85 | 86 => 7,
            80..=82 => 8,
            _ => 9,
        }]
    }

    /// The date in this language's order, e.g. "Sun, 25 October" / "So, 25. Oktober".
    pub fn date(&self, weekday: usize, day: u32, month: usize) -> String {
        self.date_pattern
            .replace("{wd}", self.days[weekday])
            .replace("{d}", &day.to_string())
            .replace("{m}", self.months[month])
    }
}

