//! Every user-visible string, in six languages. The TV's UI language picks the table
//! (Settings can override it); English is the fallback.
use std::sync::atomic::{AtomicUsize, Ordering};

/// Declares `Strings` and `Strings::texts` (every text, for glyph prewarming) in one list.
macro_rules! strings {
    ($( $(#[$meta:meta])* $field:ident : $ty:ty ),* $(,)?) => {
        pub struct Strings {
            $( $(#[$meta])* pub $field: $ty, )*
        }

        impl Strings {
            fn texts(&self) -> Vec<&'static str> {
                let mut out = Vec::new();
                $( Collect::collect(&self.$field, &mut out); )*
                out
            }
        }
    };
}

trait Collect {
    fn collect(&self, out: &mut Vec<&'static str>);
}

impl Collect for &'static str {
    fn collect(&self, out: &mut Vec<&'static str>) {
        out.push(self);
    }
}

impl<const N: usize> Collect for [&'static str; N] {
    fn collect(&self, out: &mut Vec<&'static str>) {
        out.extend_from_slice(self);
    }
}

